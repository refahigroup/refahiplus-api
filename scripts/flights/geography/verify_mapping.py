"""Verify the complete geography release on a disposable network-isolated PostgreSQL 17 container."""
import argparse
import json
import subprocess
import time
import uuid
from pathlib import Path
from prepare_evidence import load
from build_mapping import ROOT, VERSION, sql_literal

REPO = ROOT.parents[2]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--release',type=Path,default=ROOT/'2026-10-20')
    args=parser.parse_args()
    name = 'codex-flight-geo-' + uuid.uuid4().hex[:10]
    def docker(*args, input=None, check=True):
        r = subprocess.run(['docker', *args], input=input, text=True, encoding='utf-8', capture_output=True)
        if check and r.returncode: raise RuntimeError(r.stderr[-5000:])
        return r
    def sql(db, text, check=True):
        return docker('exec','-i',name,'psql','-X','-U','postgres','-d',db,'-Atq','-v','ON_ERROR_STOP=1',input=text,check=check)
    def run(db, path, check=True): return sql(db,path.read_text(encoding='utf-8-sig'),check)
    def value(db, text): return sql(db,text).stdout.strip()
    release = args.release.resolve()
    verify_file=release/'03-verify.sql' if (release/'03-verify.sql').exists() else ROOT/'03-verify.sql'
    rollback_file=release/'04-rollback-data.sql' if (release/'04-rollback-data.sql').exists() else ROOT/'04-rollback-data.sql'
    source = load(release/'inputs/geography.json.gz')
    report = load(release/'mapping-report.json.gz')
    schema = ROOT/'.local/full-schema.sql'
    if not schema.exists():
        schema.parent.mkdir(exist_ok=True)
        subprocess.run(['dotnet','ef','migrations','script','--idempotent','--project',
            str(REPO/'src/Refahi.Modules.Flights.Infrastructure'),'--startup-project',
            str(REPO/'src/Refahi.Modules.Flights.Infrastructure'),'--context','FlightsDbContext',
            '--output',str(schema)],check=True,cwd=REPO)
    docker('run','--rm','--detach','--network','none','--name',name,'-e','POSTGRES_HOST_AUTH_METHOD=trust','postgres:17-alpine')
    try:
        for _ in range(80):
            logs=docker('logs',name).stdout
            if 'init process complete' in logs and docker('exec',name,'pg_isready','-U','postgres',check=False).returncode == 0: break
            time.sleep(.25)
        else: raise RuntimeError('Disposable PostgreSQL did not finish initialization')
        docker('exec',name,'createdb','-U','postgres','baseline')
        sql('baseline','''CREATE SCHEMA "references";
CREATE TABLE "references".provinces("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text UNIQUE NOT NULL,"SortOrder" int NOT NULL,"IsActive" boolean NOT NULL);
CREATE TABLE "references".cities("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text NOT NULL,"ProvinceId" int NOT NULL REFERENCES "references".provinces("Id"),"SortOrder" int NOT NULL,"IsActive" boolean NOT NULL,UNIQUE("ProvinceId","Slug"));''')
        hotels = REPO/'scripts/hotels/geography'
        run('baseline',hotels/'fixtures/reference-geography.sql')
        run('baseline',hotels/'2026-10-19-v4/2026-10-19-v4-complete.sql')
        run('baseline',schema)
        for key, table in [('airports','airports'),('search_cities','search_cities'),('search_memberships','search_memberships')]:
            sql('baseline',f'INSERT INTO flights.{table} SELECT (jsonb_populate_record(NULL::flights.{table},r)).* FROM jsonb_array_elements({sql_literal(source[key])}::jsonb) r;')
        snapshot_sql = '''SELECT md5((SELECT jsonb_agg(to_jsonb(a) ORDER BY iata_code)::text FROM flights.airports a)||
 (SELECT jsonb_agg(to_jsonb(m) ORDER BY is_domestic,city_code,airport_code)::text FROM flights.search_memberships m))'''
        raw_before = value('baseline',snapshot_sql)
        hotel_before = value('baseline','SELECT md5(jsonb_agg(to_jsonb(m) ORDER BY "ProviderCityId")::text) FROM hotels.snapptrip_city_mappings m')
        for db in ['fresh','drift','timestamp_drift','conflict','new_identity_conflict','fk','rollback_conflict']:
            docker('exec',name,'createdb','-U','postgres','-T','baseline',db)
        run('fresh',release/'01-schema.sql')
        if report['version'] != VERSION:
            sql('fresh',"SET TIME ZONE 'Asia/Tehran';\n"+(release/'02-data.sql').read_text(encoding='utf-8'))
        run('fresh',release/'02-data.sql')
        run('fresh',release/'02-data.sql')
        assert int(value('fresh','SELECT count(*) FROM flights.airport_geography_mappings')) == len(report['airports'])
        assert int(value('fresh','SELECT count(*) FROM flights.snapptrip_city_mappings')) == len(report['commercial'])
        assert raw_before == value('fresh',snapshot_sql)
        assert hotel_before == value('fresh','SELECT md5(jsonb_agg(to_jsonb(m) ORDER BY "ProviderCityId")::text) FROM hotels.snapptrip_city_mappings m')
        assert int(value('fresh','SELECT count(*) FROM "references".cities')) == len(source['cities'])+len(report['additions']['cities'])
        assert value('fresh','SELECT count(*) FROM "references".provinces WHERE "CountryCode"<>\'IR\' AND NOT "IsSynthetic"') == '0'
        # Actual YXU stays Canadian even though commercial LON is a British destination.
        assert value('fresh','''SELECT p."CountryCode" FROM flights.airport_geography_mappings m JOIN "references".cities c ON c."Id"=m."CityId" JOIN "references".provinces p ON p."Id"=c."ProvinceId" WHERE m."AirportIataCode"='YXU' ''') == 'CA'
        run('fresh',verify_file)
        sql('drift',"UPDATE flights.airports SET city_name_en='drift' WHERE iata_code='THR'")
        failed = run('drift',release/'02-data.sql',False)
        assert failed.returncode and 'snapshot drift' in failed.stderr
        sql('timestamp_drift',"UPDATE flights.airports SET imported_at_utc=imported_at_utc+interval '1 second' WHERE iata_code='THR'")
        failed=run('timestamp_drift',release/'02-data.sql',False)
        assert failed.returncode and 'snapshot drift' in failed.stderr
        row = report['airports'][0]
        sql('conflict',f'''INSERT INTO flights.airport_geography_mappings VALUES({sql_literal(row['code'])},1,'conflict','test','{{}}','test','2026-10-20',now())''')
        failed = run('conflict',release/'02-data.sql',False)
        assert failed.returncode and 'mapping conflict' in failed.stderr
        new = report['additions']['cities'][0]
        sql('new_identity_conflict',f'''INSERT INTO "references".cities("Id","Name","NameEn","Slug","ProvinceId","SortOrder","IsActive") VALUES({new['Id']},'conflict','conflict','conflict',1,0,true)''')
        failed=run('new_identity_conflict',release/'02-data.sql',False)
        assert failed.returncode and 'identity conflict' in failed.stderr
        for db in ['drift','conflict']:
            assert value(db,'SELECT count(*) FROM "references".cities') == str(len(source['cities']))
        run('fk',release/'02-data.sql')
        failed=sql('fk',f'''DELETE FROM "references".cities WHERE "Id"={row['city_id']}''',False)
        assert failed.returncode and 'foreign key' in failed.stderr
        run('rollback_conflict',release/'02-data.sql')
        sql('rollback_conflict',f'''UPDATE flights.airport_geography_mappings SET "Evidence"='{{"changed":true}}' WHERE "AirportIataCode"={sql_literal(row['code'])}''')
        failed=run('rollback_conflict',rollback_file,False)
        assert failed.returncode and 'rollback stopped' in failed.stderr
        assert int(value('rollback_conflict','SELECT count(*) FROM flights.airport_geography_mappings'))==len(report['airports'])
        run('fresh',rollback_file)
        run('fresh',rollback_file)
        assert value('fresh','SELECT count(*) FROM flights.airport_geography_mappings')=='0'
        run('fresh',release/'02-data.sql')
        assert raw_before == value('fresh',snapshot_sql)
        print('PASS: PostgreSQL 17 install/replay; actual YXU; all raw identities/memberships and Hotels preserved; snapshot/mapping/new-ID conflict rollback; FK restrictions; guarded rollback/reinstall.')
    finally:
        docker('stop',name)


if __name__ == '__main__': main()
