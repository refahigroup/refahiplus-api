"""Validate V2 on a disposable PostgreSQL 17 container; never connect to the application DB."""
import argparse
import json
import subprocess
import tempfile
import uuid
from pathlib import Path
from build_mapping import read_reference_rows


def main(dump,version=2):
    folder=Path(__file__).parent
    report=json.loads((folder/f'2026-10-19-v{version}/mapping-report.json').read_text(encoding='utf-8'))
    baseline=json.loads((folder/'2026-10-19-v2/mapping-report.json').read_text(encoding='utf-8'))
    source=dump.read_text(encoding='utf-8-sig')
    container='codex-geography-test-'+uuid.uuid4().hex[:10]
    def docker(*args,check=True):
        result=subprocess.run(['docker',*args],capture_output=True,text=True,encoding='utf-8')
        if check and result.returncode:raise RuntimeError(result.stderr)
        return result
    def sql(db,statement):return docker('exec',container,'psql','-U','postgres','-d',db,'-v','ON_ERROR_STOP=1','-Atq','-c',statement).stdout.strip()
    def run(db,file,check=True):return docker('exec',container,'psql','-U','postgres','-d',db,'-v','ON_ERROR_STOP=1','-Atq','-f','/tmp/'+file,check=check)
    def lit(v):
        if isinstance(v,bool):return 'true' if v else 'false'
        if isinstance(v,int):return str(v)
        return "'"+v.replace("'","''")+"'"
    fixture='''CREATE SCHEMA "references";
CREATE TABLE "references".provinces("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text UNIQUE NOT NULL,"SortOrder" integer NOT NULL,"IsActive" boolean NOT NULL);
CREATE TABLE "references".cities("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text NOT NULL,"ProvinceId" integer NOT NULL REFERENCES "references".provinces("Id"),"SortOrder" integer NOT NULL,"IsActive" boolean NOT NULL,UNIQUE("ProvinceId","Slug"));
'''
    for table in ['provinces','cities']:
        rows=read_reference_rows(source,table);cols=list(rows[0])
        fixture+='INSERT INTO "references".'+table+'('+','.join('"'+c+'"' for c in cols)+') VALUES '+',\n'.join('('+','.join(lit(r[c]) for c in cols)+')' for r in rows)+';\n'
    fixture+='''CREATE SCHEMA identity;CREATE TABLE identity.user_addresses(id int,city_id int);INSERT INTO identity.user_addresses VALUES(1,1144);
CREATE SCHEMA store;CREATE TABLE store.shops(id int,"CityId" int);INSERT INTO store.shops VALUES(1,1175);
CREATE SCHEMA supplychain;CREATE TABLE supplychain.suppliers(id int,"CityId" int);INSERT INTO supplychain.suppliers VALUES(1,1178);
CREATE TABLE "references".test_fk(id int,city_id int REFERENCES "references".cities("Id"));INSERT INTO "references".test_fk VALUES(1,1186);
CREATE SCHEMA hotels;CREATE TABLE hotels.hotel_requests(id int,city_id int);INSERT INTO hotels.hotel_requests VALUES(1,1144);
'''
    docker('run','--rm','--detach','--network','none','--name',container,'-e','POSTGRES_PASSWORD=isolated-geography-test','-e','POSTGRES_DB=fresh','postgres:17-alpine')
    try:
        for _ in range(40):
            ready=docker('exec',container,'pg_isready','-U','postgres',check=False)
            if ready.returncode==0:break
            import time
            time.sleep(.25)
        else:raise RuntimeError('PostgreSQL did not start')
        with tempfile.TemporaryDirectory() as tmp:
            file=Path(tmp)/'fixture.sql';file.write_text(fixture,encoding='utf-8')
            docker('cp',str(file),container+':/tmp/fixture.sql')
        docker('cp',str(folder/'2026-10-19/2026-10-19-provider-geography.sql'),container+':/tmp/v1.sql')
        docker('cp',str(folder/'2026-10-19-v2/2026-10-19-v2-reference-geography.sql'),container+':/tmp/v2.sql')
        docker('cp',str(folder/f'2026-10-19-v{version}/2026-10-19-v{version}-reference-geography.sql'),container+':/tmp/latest.sql')
        for db in ['fresh','upgrade','from_v2','conflicting_fk']:
            if db!='fresh':docker('exec',container,'createdb','-U','postgres',db)
            run(db,'fixture.sql')
        run('fresh','latest.sql');run('fresh','latest.sql')
        run('from_v2','v2.sql');run('from_v2','latest.sql');run('from_v2','latest.sql')
        run('upgrade','v1.sql')
        sql('upgrade','''INSERT INTO "references".provider_city_mappings("Provider","ProviderCityId","CityId","ProviderCityName","CountryCode","MatchMethod","Evidence","SourceSnapshotDate") VALUES('SnappTrip','legacy-duplicate',1144,'preserve test','IR','test','{}','2026-10-10')''')
        sql('upgrade','''SELECT setval(pg_get_serial_sequence('"references".cities','Id'),900000,true)''')
        run('upgrade','latest.sql');run('upgrade','latest.sql')
        for db in ['fresh','upgrade','from_v2']:
            assert sql(db,'SELECT city_id FROM identity.user_addresses')=='1138'
            assert sql(db,'SELECT "CityId" FROM store.shops')=='1147'
            assert sql(db,'SELECT "CityId" FROM supplychain.suppliers')=='1157'
            assert sql(db,'SELECT city_id FROM "references".test_fk')=='1142'
            assert sql(db,'SELECT city_id FROM hotels.hotel_requests')=='1144', 'Native provider city ID was changed'
            assert int(sql(db,'SELECT count(*) FROM "references".cities'))==1319-4+len(report['added_cities'])
            assert sql(db,'SELECT count(*) FROM "references".city_merge_history')=='4'
            assert sql(db,"SELECT to_regclass('\"references\".provider_city_mappings') IS NULL")=='t'
            assert int(sql(db,'SELECT count(*) FROM "references".countries'))==len(report['countries'])
            assert sql(db,"SELECT count(*) FROM (SELECT \"ProvinceId\",\"references\".city_name_key(\"Name\") FROM \"references\".cities GROUP BY 1,2 HAVING count(*)>1) x")=='0'
            for provider,prefix in [('SnappTrip','snapptrip'),('Lamasoo','lamaso')]:
                actual=dict(line.split('|') for line in sql(db,f'SELECT "ProviderCityId","CityId" FROM hotels.{prefix}_city_mappings').splitlines())
                expected={r['external_id']:str(r['reference_id']) for r in report['cities'] if r['provider']==provider and r['reference_id']}
                assert all(actual.get(key)==value for key,value in expected.items()),provider
                assert len(actual)==len(expected)+(1 if db=='upgrade' and provider=='SnappTrip' else 0)
                old={r['external_id']:str(r['reference_id']) for r in baseline['cities'] if r['provider']==provider and r['reference_id']}
                assert all(actual.get(key)==value for key,value in old.items()),'V2 mapping changed'
            assert report['added_cities'][:len(baseline['added_cities'])]==baseline['added_cities'],'V2 city IDs changed'
        assert sql('upgrade',"SELECT \"CityId\" FROM hotels.snapptrip_city_mappings WHERE \"ProviderCityId\"='legacy-duplicate'")=='1138'
        assert int(sql('upgrade',"SELECT nextval(pg_get_serial_sequence('\"references\".cities','Id'))"))>900000
        # A live mapping conflict must abort instead of overwriting another decision.
        sql('fresh',"UPDATE hotels.snapptrip_city_mappings SET \"CityId\"=1 WHERE \"ProviderCityId\"='7457'")
        result=run('fresh','latest.sql',check=False)
        assert result.returncode and 'Existing city mapping conflicts' in result.stderr,result.stderr
        assert sql('fresh',"SELECT \"CityId\" FROM hotels.snapptrip_city_mappings WHERE \"ProviderCityId\"='7457'")=='1'
        sql('fresh',"UPDATE \"references\".cities SET \"Name\"='DRIFT' WHERE \"Id\"=354")
        result=run('fresh','latest.sql',check=False)
        assert result.returncode and 'Reference snapshot' in result.stderr,result.stderr
        # An unrelated business uniqueness conflict cannot silently delete a related record.
        sql('conflicting_fk','''CREATE TABLE "references".owner_city(owner_id int,city_id int REFERENCES "references".cities("Id"),UNIQUE(owner_id,city_id));INSERT INTO "references".owner_city VALUES(1,1138),(1,1144)''')
        result=run('conflicting_fk','latest.sql',check=False)
        assert result.returncode and 'duplicate key' in result.stderr,result.stderr
        assert sql('conflicting_fk','SELECT count(*) FROM "references".cities')=='1319'
        assert sql('conflicting_fk','SELECT count(*) FROM "references".owner_city')=='2'
        print(f'PASS V{version}: fresh/repeat, V1/V2 upgrades, all mapping targets, V2 IDs stable, logical/FK references, native IDs unchanged, dedup uniqueness, sequence high-water mark, mapping/reference/FK conflict rollback.')
    finally:
        docker('stop',container)


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--dump',type=Path,required=True)
    parser.add_argument('--version',type=int,choices=[2,3],default=2)
    args=parser.parse_args();main(args.dump,args.version)
