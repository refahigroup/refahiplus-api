"""Exercise V4 complete and upgrade scripts on a disposable network-isolated PostgreSQL."""
import json
import argparse
import subprocess
import tempfile
import time
import uuid
from pathlib import Path
from build_mapping import read_reference_rows
from build_mapping_v4 import literal


def main(dump=None):
    root=Path(__file__).parent
    baseline=json.loads((root/'2026-10-19-v3/mapping-report.json').read_text(encoding='utf-8'))
    report=json.loads((root/'2026-10-19-v4/mapping-report.json').read_text(encoding='utf-8'))
    dump=dump or root/'fixtures/reference-geography.sql'
    source=dump.read_text(encoding='utf-8-sig');container='codex-geography-v4-'+uuid.uuid4().hex[:10]
    def docker(*args,check=True):
        r=subprocess.run(['docker',*args],capture_output=True,text=True,encoding='utf-8')
        if check and r.returncode:raise RuntimeError(r.stderr[:4000])
        return r
    def sql(db,text):return docker('exec',container,'psql','-U','postgres','-d',db,'-v','ON_ERROR_STOP=1','-Atq','-c',text).stdout.strip()
    def run(db,file,check=True):return docker('exec',container,'psql','-U','postgres','-d',db,'-v','ON_ERROR_STOP=1','-Atq','-f','/tmp/'+file,check=check)
    fixture='''CREATE SCHEMA "references";
CREATE TABLE "references".provinces("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text UNIQUE NOT NULL,"SortOrder" int NOT NULL,"IsActive" boolean NOT NULL);
CREATE TABLE "references".cities("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text NOT NULL,"ProvinceId" int NOT NULL REFERENCES "references".provinces("Id"),"SortOrder" int NOT NULL,"IsActive" boolean NOT NULL,UNIQUE("ProvinceId","Slug"));
'''
    for table in ['provinces','cities']:
        rows=read_reference_rows(source,table);cols=list(rows[0])
        fixture+='INSERT INTO "references".'+table+'('+','.join('"'+c+'"' for c in cols)+') VALUES '+',\n'.join('('+','.join(literal(r[c]) for c in cols)+')' for r in rows)+';\n'
    fixture+='''CREATE SCHEMA hotels;CREATE TABLE hotels.hotel_requests(city_id int,province_id int);INSERT INTO hotels.hotel_requests VALUES(1144,46);
CREATE SCHEMA store;CREATE TABLE store.shops("CityId" int,"ProvinceId" int);INSERT INTO store.shops VALUES(1335,46);
'''
    docker('run','--rm','--detach','--network','none','--name',container,'-e','POSTGRES_PASSWORD=isolated-geography-test','-e','POSTGRES_DB=base','postgres:17-alpine')
    try:
        for _ in range(40):
            if docker('exec',container,'pg_isready','-U','postgres',check=False).returncode==0:break
            time.sleep(.25)
        else:raise RuntimeError('PostgreSQL startup failed')
        with tempfile.TemporaryDirectory() as tmp:
            file=Path(tmp)/'fixture.sql';file.write_text(fixture,encoding='utf-8');docker('cp',str(file),container+':/tmp/fixture.sql')
        for name,path in [('v1.sql',root/'2026-10-19/2026-10-19-provider-geography.sql'),
                          ('v2.sql',root/'2026-10-19-v2/2026-10-19-v2-reference-geography.sql'),
                          ('v3.sql',root/'2026-10-19-v3/2026-10-19-v3-reference-geography.sql'),
                          ('v4.sql',root/'2026-10-19-v4/2026-10-19-v4-upgrade.sql'),
                          ('complete.sql',root/'2026-10-19-v4/2026-10-19-v4-complete.sql')]:docker('cp',str(path),container+':/tmp/'+name)
        run('base','fixture.sql');run('base','v3.sql')
        sql('base','''CREATE TABLE "references".test_province_fk(id int,province_id int REFERENCES "references".provinces("Id"));INSERT INTO "references".test_province_fk VALUES(1,46);
SELECT setval(pg_get_serial_sequence('"references".cities','Id'),900000,true)''')
        for db in ['upgraded','drift','collision','mapping_conflict','new_id_conflict']:
            docker('exec',container,'createdb','-U','postgres','-T','base',db)
        for db,prior in [('fresh',None),('from_v1','v1.sql'),('from_v2','v2.sql')]:
            docker('exec',container,'createdb','-U','postgres',db);run(db,'fixture.sql')
            if prior:run(db,prior)
            run(db,'complete.sql');run(db,'complete.sql')
        run('upgraded','v4.sql');run('upgraded','complete.sql');run('upgraded','v4.sql')
        for db in ['fresh','from_v1','from_v2','upgraded']:
            assert sql(db,'SELECT count(*) FROM "references".cities')=='1415'
            assert sql(db,'SELECT count(*) FROM "references".provinces')=='45'
            assert sql(db,'SELECT count(*) FROM "references".provinces WHERE "CountryCode"=\'IR\' AND NOT "IsSynthetic"')=='31'
            assert sql(db,'SELECT count(*) FROM "references".provinces WHERE "CountryCode"<>\'IR\' AND NOT "IsSynthetic"')=='0'
            assert sql(db,'SELECT count(*) FROM "references".countries')=='15'
            assert sql(db,'SELECT count(*) FROM "references".province_reorganization_history')=='29'
            assert sql(db,'SELECT "ProvinceId" FROM store.shops')=='32'
            assert sql(db,'SELECT city_id||\'|\'||province_id FROM hotels.hotel_requests')=='1144|46'
            assert sql(db,'SELECT count(*) FROM hotels.lamaso_city_mappings')=='706'
            assert sql(db,'SELECT count(*) FROM hotels.snapptrip_city_mappings')=='316'
            assert sql(db,'SELECT count(*) FROM hotels.lamaso_city_mappings WHERE NOT "IsEnabled"')=='1'
            for provider,prefix in [('Lamasoo','lamaso'),('SnappTrip','snapptrip')]:
                actual=dict(line.split('|') for line in sql(db,f'SELECT "ProviderCityId","CityId" FROM hotels.{prefix}_city_mappings').splitlines())
                assert all(actual.get(r['external_id'])==str(r['reference_id']) for r in baseline['cities'] if r['provider']==provider and r['reference_id'])
            for row in report['mappings']:
                assert sql(db,'SELECT "CityId"||\'|\'||"CountryCode"||\'|\'||"IsEnabled" FROM hotels.lamaso_city_mappings WHERE "ProviderCityId"='+literal(row['provider_city_id']))==f"{row['city_id']}|{row['country']}|{str(row['enabled']).lower()}"
        assert sql('upgraded','SELECT province_id FROM "references".test_province_fk')=='32'
        assert int(sql('upgraded',"SELECT nextval(pg_get_serial_sequence('\"references\".cities','Id'))"))>900000
        sql('drift','UPDATE "references".provinces SET "Name"=\'DRIFT\' WHERE "Id"=46')
        failure=run('drift','complete.sql',check=False);assert failure.returncode and 'Province ID/country conflict' in failure.stderr,failure.stderr[:4000]
        assert sql('drift','SELECT count(*) FROM "references".provinces')=='60'
        sql('collision','''INSERT INTO "references".cities("Id","Name","NameEn","Slug","ProvinceId","SortOrder","IsActive") VALUES(2000,'ترابزون','collision','collision',46,2000,true)''')
        failure=run('collision','v4.sql',check=False);assert failure.returncode and 'City names collide' in failure.stderr,failure.stderr
        assert sql('collision','SELECT "ProvinceId" FROM store.shops')=='46'
        sql('mapping_conflict','''INSERT INTO hotels.lamaso_city_mappings("ProviderCityId","CityId","ProviderCityName","CountryCode","MatchMethod","Evidence","SourceSnapshotDate") VALUES('66a4bc1c484b40ce7afccc32',252,'رضوانشهر','IR','test','{}','2026-10-19')''')
        failure=run('mapping_conflict','v4.sql',check=False);assert failure.returncode and 'Existing provider mapping conflicts' in failure.stderr,failure.stderr
        assert sql('mapping_conflict','SELECT count(*) FROM "references".provinces')=='60'
        sql('new_id_conflict','''INSERT INTO "references".cities("Id","Name","NameEn","Slug","ProvinceId","SortOrder","IsActive") VALUES(1415,'LIVE DATA','live','live',1,1415,true)''')
        failure=run('new_id_conflict','v4.sql',check=False);assert failure.returncode and 'New confirmed city ID/name conflicts' in failure.stderr,failure.stderr
        assert sql('new_id_conflict','SELECT count(*) FROM "references".provinces')=='60'
        print('PASS V4: fresh/V1/V2/V3 installation and replay; 10 reviewed mappings; country buckets and history; declared/logical references; disabled caption; V3/native IDs and sequence preserved; drift, collisions, mapping and new-ID conflicts roll back.')
    finally:docker('stop',container)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dump',type=Path,default=Path(__file__).parent/'fixtures/reference-geography.sql')
    main(parser.parse_args().dump)
