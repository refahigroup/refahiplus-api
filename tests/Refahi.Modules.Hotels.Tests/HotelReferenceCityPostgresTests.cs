using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.Extensions.DependencyInjection;
using Npgsql;
using Refahi.Modules.Hotels.Domain.Aggregates.Catalogue;
using Refahi.Modules.Hotels.Infrastructure.Persistence;
using Refahi.Modules.Hotels.Infrastructure.Persistence.Repositories;
using Xunit;

namespace Refahi.Modules.Hotels.Tests;

public sealed class HotelReferenceCityPostgresTests
{
    // Run only against an explicitly supplied disposable database; never application configuration.
    private sealed class DisposablePostgresFactAttribute : FactAttribute
    {
        public DisposablePostgresFactAttribute()
        {
            if (string.IsNullOrEmpty(Environment.GetEnvironmentVariable("REFAHI_HOTEL_TEST_DATABASE")))
                Skip = "Set REFAHI_HOTEL_TEST_DATABASE to a disposable hotel_city_test database.";
        }
    }

    [DisposablePostgresFact]
    public async Task V4MappingsAndListingUpgrade_PreserveNativeAndHistoricalIdentities()
    {
        var connection = Environment.GetEnvironmentVariable("REFAHI_HOTEL_TEST_DATABASE")!;
        Assert.StartsWith("hotel_city_test", new NpgsqlConnectionStringBuilder(connection).Database);
        var services = new ServiceCollection();
        services.AddDbContext<HotelsDbContext>(o => o.UseNpgsql(connection));
        await using var provider = services.BuildServiceProvider();
        await using var scope = provider.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<HotelsDbContext>();
        var migrator = db.GetService<IMigrator>();
        var previous = db.Database.GetMigrations().TakeWhile(x => !x.EndsWith("HotelsReferenceCitySearch")).Last();
        await migrator.MigrateAsync(previous);
        var missing = await Assert.ThrowsAsync<PostgresException>(() => db.Database.MigrateAsync());
        Assert.Contains("V4 must be installed", missing.MessageText);
        await db.Database.ExecuteSqlRawAsync("""
            CREATE SCHEMA "references";
            CREATE TABLE "references".provinces("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text UNIQUE NOT NULL,"SortOrder" int NOT NULL,"IsActive" boolean NOT NULL);
            CREATE TABLE "references".cities("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"Name" text NOT NULL,"NameEn" text NOT NULL,"Slug" text NOT NULL,"ProvinceId" int NOT NULL REFERENCES "references".provinces("Id"),"SortOrder" int NOT NULL,"IsActive" boolean NOT NULL,UNIQUE("ProvinceId","Slug"));
            """);
        await ExecuteFile(db, "reference-geography.sql");
        await ExecuteFile(db, "geography-v4.sql");
        var hotelKey = Guid.NewGuid(); var legacyCityKey = Guid.NewGuid();
        await db.Database.ExecuteSqlInterpolatedAsync($"""
            INSERT INTO hotels.catalogue_listings("HotelKey","CityKey","Provider","NativeId","NativeCityId")
            VALUES ({hotelKey},{legacyCityKey},'SnappTrip','historic-hotel','6433');
            """);
        await migrator.MigrateAsync(db.Database.GetMigrations().Single(x => x.EndsWith("HotelsReferenceCitySearch")));
        var reservationId = Guid.NewGuid();
        await db.Database.ExecuteSqlInterpolatedAsync($"""
            INSERT INTO hotels.external_reservations("HotelRequestId","Provider","ReferenceId","RequestHash","SubmitJson","State","SupplyPriceMinor","FeeMinor","LockedUntilUtc","ReservationId","ResponseSnapshot","UpdatedAtUtc","Version")
            VALUES ({reservationId},'Unexpected','historic-reference','historic-hash',jsonb_build_object(),5,900,9,now() + interval '15 minutes',NULL,jsonb_build_object(),now(),3);
            """);
        var unexpected = await Assert.ThrowsAsync<PostgresException>(() => db.Database.MigrateAsync());
        Assert.Contains("Unexpected provider", unexpected.MessageText);
        await db.Database.ExecuteSqlRawAsync("UPDATE hotels.external_reservations SET \"Provider\" = 'Lamasoo'");
        await migrator.MigrateAsync(db.Database.GetMigrations().Single(x=>x.EndsWith("HotelsDiscovery")));
        var oldSuccess=DateTimeOffset.FromUnixTimeSeconds(DateTimeOffset.UtcNow.ToUnixTimeSeconds()-3600);
        await db.Database.ExecuteSqlInterpolatedAsync($"""
            INSERT INTO hotels.snapptrip_discovery_sync_states("NativeCityId","LastSuccessAtUtc","NextAttemptAtUtc","Status")
            VALUES ('migration-fixture',{oldSuccess},{oldSuccess.AddHours(24)},'ready')
            """);
        await db.Database.MigrateAsync();
        var sync=await db.Set<SnappTripDiscoverySyncState>().SingleAsync(x=>x.NativeCityId=="migration-fixture");
        Assert.Equal(oldSuccess,sync.LastSuccessAtUtc);Assert.True(sync.NextAttemptAtUtc<=DateTimeOffset.UtcNow);
        var migrated = await db.Set<HotelExternalReservation>().SingleAsync(x => x.HotelRequestId == reservationId);
        Assert.Equal("historic-reference", migrated.ReferenceId); Assert.Equal("historic-hash", migrated.RequestHash);
        Assert.Equal("{}", migrated.SubmitJson); Assert.Equal(891, migrated.HotelShareMinor);
        Assert.True(migrated.ConfirmationAttempted); Assert.False(migrated.NoExternalLiability);
        Assert.Equal(HotelExternalState.Unknown, migrated.State);
        Assert.Contains(await new HotelCatalogueRepository(db).RecoveryAsync(true, default), x => x.HotelRequestId == reservationId);
        Assert.Empty(await db.Set<HotelExternalOperation>().ToListAsync());
        Assert.False(db.Database.HasPendingModelChanges());
        var mapping = new HotelCityMappingRepository(provider.GetRequiredService<IServiceScopeFactory>());
        var canonical = await db.Set<SnappTripCityMapping>().SingleAsync(x => x.ProviderCityId == "6433");
        var listing = await db.Set<HotelListing>().SingleAsync(x => x.HotelKey == hotelKey);
        Assert.Equal(canonical.CityId, listing.ReferenceCityId); Assert.Equal(legacyCityKey, listing.CityKey);
        Assert.Equal("6433", listing.NativeCityId);
        Assert.Contains("6433", await mapping.SnappTripCityIdsAsync(canonical.CityId, default));
        var disabled = await db.Set<LamasoCityMapping>().SingleAsync(x => !x.IsEnabled);
        Assert.DoesNotContain(disabled.ProviderCityId, await mapping.LamasoCityIdsAsync(disabled.CityId, default));
        Assert.Empty(await mapping.LamasoCityIdsAsync(-1, default));
        var concurrent = await Task.WhenAll(mapping.SnappTripCityIdsAsync(canonical.CityId, default), mapping.LamasoCityIdsAsync(disabled.CityId, default));
        Assert.Equal(2, concurrent.Length);
        var fresh = HotelListing.Create(canonical.CityId, "SnappTrip", "new-hotel", "6433");
        db.Add(fresh); await db.SaveChangesAsync();
        Assert.Null(fresh.CityKey); Assert.NotEqual(hotelKey, fresh.HotelKey);
        // A replay must not reassign public hotel keys or overwrite reviewed mapping rows.
        await db.Database.MigrateAsync();
        Assert.Equal(hotelKey, (await db.Set<HotelListing>().SingleAsync(x => x.NativeId == "historic-hotel")).HotelKey);
        Assert.Equal(316, await db.Set<SnappTripCityMapping>().CountAsync());
        Assert.Equal(706, await db.Set<LamasoCityMapping>().CountAsync());
        var attempt = HotelExternalOperation.Start(migrated, HotelExternalOperationKind.Inquiry); db.Add(attempt); await db.SaveChangesAsync();
        await using var contender = new HotelsDbContext(new DbContextOptionsBuilder<HotelsDbContext>().UseNpgsql(connection).Options);
        var stale = await contender.Set<HotelExternalReservation>().SingleAsync(x => x.HotelRequestId == reservationId);
        migrated.ScheduleRecovery(30); await db.SaveChangesAsync();
        stale.ScheduleRecovery(60);
        await Assert.ThrowsAsync<DbUpdateConcurrencyException>(() => contender.SaveChangesAsync());
        var evidence = await contender.Set<HotelExternalOperation>().SingleAsync();
        Assert.Equal(attempt.Id, evidence.Id); Assert.Equal("historic-reference", evidence.ReferenceId);
        await HotelDiscoveryPostgresChecks.Run(db, canonical);
        await HotelLocalContentPostgresChecks.Run(db, canonical);
        var downgrade = await Assert.ThrowsAsync<PostgresException>(() => migrator.MigrateAsync(db.Database.GetMigrations().Single(x => x.EndsWith("HotelsReferenceCitySearch"))));
        Assert.Contains("Cannot downgrade", downgrade.MessageText);
    }
    private static async Task ExecuteFile(HotelsDbContext db, string name)
    {
        var sql = await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "TestData", name));
        await using var command = new NpgsqlCommand(sql, (NpgsqlConnection)db.Database.GetDbConnection()) { CommandTimeout = 120 };
        if (command.Connection!.State != System.Data.ConnectionState.Open) await command.Connection.OpenAsync();
        await command.ExecuteNonQueryAsync();
    }
}
